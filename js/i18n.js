/* tr('key') → chuỗi theo ngôn ngữ đang dùng.
   tr('key', {n:3}) → thay {n} trong chuỗi bằng 3.
   {n#task#tasks} → chọn dạng số ít hay số nhiều theo p.n. Tiếng Việt không chia số nhiều
   nên luôn lấy dạng đầu; viết bản tiếng Việt là '{n} task' và bản tiếng Anh là '{n} {n#task#tasks}'. */
const I = LANG === 'en' ? 1 : 0;
const tr = (k, p) => {
  const pair = STR[k];
  let s = pair ? (pair[I] ?? pair[0]) : k;
  if(!p) return s;
  s = s.replace(/\{(\w+)#([^#}]*)#([^}]*)\}/g, (m, x, one, many) => I && Math.abs(p[x]) !== 1 ? many : one);
  return s.replace(/\{(\w+)\}/g, (m, x) => p[x] ?? m);
};

/* Dịch phần tĩnh của index.html lúc khởi động. Mỗi thuộc tính một kiểu đích:
   data-i18n = chữ hiện ra, data-i18n-title = tooltip, data-i18n-ph = placeholder ô nhập. */
function i18nDom(root = document){
  root.querySelectorAll('[data-i18n]').forEach(e => e.textContent = tr(e.dataset.i18n));
  root.querySelectorAll('[data-i18n-title]').forEach(e => e.title = tr(e.dataset.i18nTitle));
  root.querySelectorAll('[data-i18n-ph]').forEach(e => e.placeholder = tr(e.dataset.i18nPh));
}
